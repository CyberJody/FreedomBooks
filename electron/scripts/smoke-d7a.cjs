'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
module.exports = async ({page, company, ids, invoiceId, shot, pass, heading}) => {
  const out = process.env.FB_SMOKE_SHOTS || path.resolve(__dirname,'../staging-run');
  const go = p => page.goto(`fb://app/c/${company}${p}`);
  const capture = name => shot(page, 'd7a-'+name);
  const save = (label, pattern) => Promise.all([page.waitForURL(pattern),page.getByRole('button',{name:label,exact:true}).click()]);
  try {
    await go('/lists/vendors/');
    const vendorLink = await page.locator('tbody a').filter({hasText:'Pond Supply'}).first().getAttribute('href');
    const vendor = /vendors\/([0-9a-f-]{36})/.exec(vendorLink)[1];
    await go('/checks/new/');
    assert.equal(await heading(page),'Write check / expense');
    assert.equal(await page.inputValue('#id_lines-TOTAL_FORMS'),'2');
    await page.selectOption('#id_vendor',vendor);
    assert.equal(await page.inputValue('#id_lines-0-account'),ids.expense);
    await page.fill('#id_date','2026-10-15');
    await page.check('#id_print_later');
    assert.equal(await page.inputValue('#id_check_number'),'');
    await page.fill('#id_memo','Synthetic written check\tReference #typed');
    await page.fill('#id_lines-0-description','Supplies');
    await page.fill('#id_lines-0-rate','10.25');
    await page.fill('#id_lines-1-description',' \t ');
    await capture('01-check-form-line-fields');
    await page.fill('#id_date','');
    await page.click('button:has-text("Save check")');
    await page.waitForSelector('#id_date_error');
    assert.equal(await page.inputValue('#id_lines-0-description'),'Supplies');
    assert.equal(await page.locator('#id_lines-1-rate_error').count(),0);
    await capture('02-check-invalid');
    await page.fill('#id_date','2026-10-15');
    await page.click('#add-expense-line');
    await page.selectOption('#id_lines-2-account',ids.expense);
    await page.fill('#id_lines-2-description','Added expense line');
    await page.fill('#id_lines-2-rate','2.50');
    assert.equal(await page.inputValue('#id_lines-TOTAL_FORMS'),'3');
    await save('Save check',/checks\/[0-9a-f-]{36}\/$/);
    const checkUrl=page.url();
    assert.match(await heading(page),/To print/);
    await capture('03-check-detail-document');
    await page.click('a:has-text("Edit check")');
    await page.waitForSelector('#check-entry');
    await page.fill('#id_memo','Revised synthetic check');
    await save('Save check',/checks\/[0-9a-f-]{36}\/$/);
    await page.click('a:has-text("Revision 1")');
    await page.waitForSelector('h1:has-text("Revision 1")');
    await capture('04-check-revision');
    await page.goto(checkUrl);
    await page.click('a:has-text("Review recording")');
    await page.waitForSelector('h1:has-text("Review check recording")');
    assert.match(await page.locator('main').textContent(),/12\.75/);
    await capture('05-check-review');
    await page.locator('form.bill-post').scrollIntoViewIfNeeded();
    await page.screenshot({path:path.join(out,'d7a-05b-check-posting-entries.png')});
    await save('Record check — books only',/checks\/[0-9a-f-]{36}\/$/);
    await page.click('a:has-text("Assign check number")');
    await page.waitForSelector('h1:has-text("Assign check number")');
    await page.fill('#id_check_number','7001');
    await capture('06-check-number');
    await save('Assign check number',/checks\/[0-9a-f-]{36}\/$/);
    assert.match(await heading(page),/7001/);
    await go('/checks/');
    await capture('07-check-list');
    await page.goto('fb://app'+vendorLink);
    assert.match(await page.locator('main').textContent(),/Checks written to this vendor/);
    await capture('08-vendor-activity');
    await page.locator('h3:has-text("Checks written to this vendor")').scrollIntoViewIfNeeded();
    await page.screenshot({path:path.join(out,'d7a-08b-vendor-checks.png')});
    await page.goto(checkUrl);
    await page.click('a:has-text("Void check")');
    await page.waitForSelector('#id_reason');
    await page.fill('#id_date','2026-10-20');
    await page.fill('#id_reason','Synthetic written check correction');
    await capture('09-check-void');
    await save('Void check',/checks\/[0-9a-f-]{36}\/$/);
    assert.match(await page.locator('main').textContent(),/Current check state: Voided/);
    pass('D7a check forms: vendor defaults, whitespace extra, invalid fields, add line, save/revise/history, explicit review/record, number and linked void');

    await go(`/receipts/new/?customer=${ids.customer}`);
    await page.fill('#id_date','2026-10-22');
    await page.fill('#id_amount','10.00');
    await page.selectOption('#id_method','CASH');
    await page.selectOption('#id_destination','UNDEPOSITED');
    await page.selectOption('#id_allocations-0-invoice',invoiceId);
    await page.fill('#id_allocations-0-amount','10.00');
    await page.click('button:has-text("Review receipt")');
    await page.waitForSelector('button:has-text("Record receipt — books only")');
    await save('Record receipt — books only',/receipts\/[0-9a-f-]{36}\/$/);
    await go('/sales-receipts/new/');
    await page.selectOption('#id_customer',ids.customer);
    await page.fill('#id_date','2026-10-22');
    await page.selectOption('#id_method','CASH');
    await page.selectOption('#id_destination','UNDEPOSITED');
    await page.selectOption('#id_tax_mode','NONE');
    await page.fill('#id_lines-0-description','Synthetic cash sale');
    await page.fill('#id_lines-0-quantity','2');
    await page.fill('#id_lines-0-rate','5.00');
    await page.selectOption('#id_lines-0-income_account',ids.income);
    await page.click('button:has-text("Review sales receipt")');
    await page.waitForSelector('#review-total');
    await save('Record sales receipt — books only',/sales-receipts\/[0-9a-f-]{36}\/$/);
    await go('/deposits/new/');
    assert.equal(await page.locator('input[name="receipts"]').count(),2);
    await page.selectOption('#id_bank',ids.bank);
    await page.fill('#id_date','2026-10-23');
    await page.fill('#id_reference','Synthetic slip');
    await page.fill('#id_memo','Customer payment + cash sale');
    await capture('10-deposit-form');
    await page.click('button:has-text("Review deposit")');
    await page.waitForSelector('#id_receipts_error');
    await capture('11-deposit-invalid');
    for (const checkbox of await page.locator('input[name="receipts"]').all()) await checkbox.check();
    await page.click('button:has-text("Review deposit")');
    await page.waitForSelector('.deposit-review');
    assert.equal(await page.locator('#review-total').textContent(),'20.00');
    await capture('12-deposit-review');
    await page.locator('.deposit-review').scrollIntoViewIfNeeded();
    await page.screenshot({path:path.join(out,'d7a-12b-deposit-review-entries.png')});
    await save('Record deposit — books only',/deposits\/[0-9a-f-]{36}\/$/);
    const depositUrl=page.url();
    assert.equal(await page.locator('#deposit-total').textContent(),'20.00');
    await capture('13-deposit-detail');
    await go('/deposits/');
    await capture('14-deposit-list');
    await go('/deposits/new/');
    assert.equal(await page.locator('input[name="receipts"]').count(),0);
    await page.goto(depositUrl);
    await page.click('a:has-text("Reverse deposit")');
    await page.waitForSelector('#id_reason');
    await page.fill('#id_date','2026-10-24');
    await page.fill('#id_reason','Synthetic deposit correction');
    await capture('15-deposit-reverse');
    await save('Record exact reversal',/deposits\/[0-9a-f-]{36}\/$/);
    assert.match(await page.locator('main').textContent(),/Reversed · total 20.00/);
    await capture('16-deposit-reversed');
    await go('/deposits/new/');
    assert.equal(await page.locator('input[name="receipts"]').count(),2);
    pass('D7a deposits: customer and sales receipts selected together, invalid selection, review total, record, list/detail, held receipt exclusion and exact reversal release');
  } catch (error) {
    fs.writeFileSync(path.join(out,'d7a-failure.html'),await page.content());
    await page.screenshot({path:path.join(out,'d7a-failure.png')});
    throw error;
  }
};
