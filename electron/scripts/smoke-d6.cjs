'use strict';
// D6 flow is separate so sibling waves only append their own call to smoke.cjs.
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
async function runD6({ app, page, company, ids, shot, pass, heading }) {
  const base = `fb://app/c/${company}`;
  const go = (path) => page.goto(base + path);
  const capture = (name) => shot(page, 'd6-' + name);
  const section = async (name, selector) => {
    await page.locator(selector).scrollIntoViewIfNeeded();
    await page.screenshot({path:path.join(process.env.FB_SMOKE_SHOTS || path.resolve(__dirname, '../staging-run'), 'd6-' + name + '.png')});
  };
  const save = async (label, pattern) => {
    try { return await Promise.all([page.waitForURL(pattern), page.click(`button:has-text("${label}")`)]); }
    catch (error) {
      const out = process.env.FB_SMOKE_SHOTS || path.resolve(__dirname, '../staging-run');
      fs.writeFileSync(path.join(out, 'd6-failure.html'), await page.content());
      await page.screenshot({path:path.join(out, 'd6-failure.png')});
      throw error;
    }
  };
  await go('/accounts/new/');
  await page.fill('#id_code', '1010');
  await page.fill('#id_name', 'Savings');
  await page.selectOption('#id_detail_type', 'BANK');
  await save('Save', /\/accounts\/$/);
  const accounts = await app.evaluate(({app:a},c)=>JSON.parse(process.getBuiltinModule('module').createRequire(a.getAppPath()+'/package.json')('./native/fb-node.node').query(JSON.stringify({type:'Accounts',company_id:c}))),company);
  const savings = accounts.find(a => a.code === '1010').id;
  await go('/accounting-setup/');
  await page.selectOption('#id_banks', [ids.bank, savings]);
  await save('Save accounting setup', /accounting-setup/);
  await go('/lists/vendors/');
  const vendorLink = await page.locator('tbody a').filter({ hasText: 'Pond Supply' }).first().getAttribute('href');
  const vendor = /vendors\/([0-9a-f-]{36})/.exec(vendorLink)[1];
  await page.goto('fb://app' + vendorLink + 'edit/');
  await page.selectOption('#id_default_expense_account', ids.expense);
  await page.selectOption('#id_default_terms', '30');
  await save('Save', /lists\/vendors\/[0-9a-f-]{36}\/$/);
  await go('/bills/new/');
  assert.equal(await heading(page), 'New bill');
  await page.fill('#id_date', '2026-10-01');
  await page.selectOption('#id_vendor', vendor);
  await page.waitForFunction(() => document.querySelector('#id_due_date').value === '2026-10-31');
  assert.equal(await page.inputValue('#id_lines-0-expense_account'), ids.expense);
  await page.fill('#id_reference', 'SUP-101');
  await page.fill('#id_memo', 'Synthetic parts bill\tFor the workshop');
  await page.fill('#id_lines-0-description', 'Parts & supplies');
  await page.fill('#id_lines-0-quantity', '2');
  await page.fill('#id_lines-0-rate', '25.00');
  await page.click('#add-line');
  assert.equal(await page.inputValue('#id_lines-TOTAL_FORMS'), '4');
  await capture('01-bill-form-and-line-fields');
  await page.locator('#bill-lines').scrollIntoViewIfNeeded();
  await page.screenshot({path:path.join(process.env.FB_SMOKE_SHOTS || path.resolve(__dirname, '../staging-run'), 'd6-01b-bill-line-fields.png')});
  await page.selectOption('#id_vendor', '');
  await page.click('button:has-text("Save bill")');
  await page.waitForSelector('#id_vendor_error');
  assert.equal(await page.inputValue('#id_lines-0-description'), 'Parts & supplies');
  await capture('02-bill-invalid');
  await page.selectOption('#id_vendor', vendor);
  // The frozen picker fills the next blank account when the vendor is selected again.
  // Leave unused rows wholly blank before saving the one-line bill.
  for (let i = 1; i < 4; i++) await page.selectOption(`#id_lines-${i}-expense_account`, '');
  await save('Save bill', /bills\/[0-9a-f-]{36}\/$/);
  const billUrl = page.url();
  assert.match(await heading(page), /Bill BILL-000001/);
  await capture('03-bill-detail-and-document');
  await page.click('a:has-text("Edit bill")');
  await page.waitForSelector('#id_lines-0-origin_position', {state:'attached'});
  await page.fill('#id_memo', 'Revised synthetic bill');
  await save('Save bill', /bills\/[0-9a-f-]{36}\/$/);
  await page.click('a:has-text("Revision 1")');
  await page.waitForSelector('h1:has-text("Historical revision 1")');
  await capture('04-bill-revision');
  await page.goto(billUrl);
  await page.click('a:has-text("Review posting")');
  await page.waitForSelector('h1:has-text("Review bill posting")');
  assert.match(await page.locator('main').textContent(), /Expense account \(line 1\)/);
  await capture('05-bill-review');
  await section('05b-bill-posting-entries', 'form.bill-post');
  await save('Post bill', /bills\/[0-9a-f-]{36}\/$/);
  assert.equal(await page.locator('#outstanding').textContent(), '50.00');
  await go('/bills/');
  await capture('06-bill-list');
  await go('/bills/calendar/?year=2026&month=10');
  assert.equal(await page.locator('#month-total').textContent(), '50.00');
  await capture('07-bill-calendar');
  await section('07b-calendar-agenda', '.calendar-agenda');
  await page.click('a.pay-link');
  await page.waitForSelector('#payment-entry');
  await page.fill('#id_date', '2026-10-31');
  await page.fill('#id_amount', '20.00');
  assert.equal(await page.inputValue('#id_reference'), '1');
  const billId = /bills\/([0-9a-f-]{36})/.exec(billUrl)[1];
  await page.selectOption('#id_allocations-0-bill', billId);
  await page.fill('#id_allocations-0-amount', '20.00');
  await page.click('#add-allocation');
  assert.equal(await page.inputValue('#id_allocations-TOTAL_FORMS'), '4');
  await capture('08-payment-form');
  assert.equal(await page.locator('#payment-entry').evaluate(f => f.checkValidity()), true);
  await page.click('button:has-text("Review payment")');
  await page.waitForSelector('.payment-review, #payment-entry .errorlist', {timeout:30000});
  assert.equal(await page.locator('.payment-review').count(), 1, await page.locator('main').textContent());
  assert.match(await page.locator('.payment-review').textContent(), /20\.00/);
  await capture('09-payment-review');
  await section('09b-payment-review-entries', '.payment-review');
  await save('Record payment — books only', /payments\/[0-9a-f-]{36}\/$/);
  const paymentUrl = page.url();
  await capture('10-payment-detail');
  await page.goto(billUrl);
  assert.equal(await page.locator('#outstanding').textContent(), '30.00');
  await go('/payments/');
  await capture('11-payment-list');
  await go('/payments/new/?vendor=' + vendor);
  assert.equal(await page.inputValue('#id_reference'), '2');
  await page.goto(paymentUrl);
  await page.click('a:has-text("Reverse payment")');
  await page.waitForSelector('h1:has-text("Reverse payment")');
  await page.fill('#id_date', '2026-10-31');
  await page.fill('#id_reason', 'Synthetic correction');
  await capture('12-payment-reverse');
  await save('Record exact reversal', /payments\/[0-9a-f-]{36}\/$/);
  assert.match(await page.locator('main').textContent(), /Reversed/);
  await page.goto(billUrl);
  assert.equal(await page.locator('#outstanding').textContent(), '50.00');
  await page.click('a:has-text("Void bill")');
  await page.waitForSelector('h1:has-text("Void BILL")');
  await page.fill('#id_date', '2026-10-31');
  await page.fill('#id_reason', 'Duplicate supplier bill');
  await capture('13-bill-void');
  await save('Void bill', /bills\/[0-9a-f-]{36}\/$/);
  assert.match(await page.locator('main').textContent(), /Current bill state: Voided/);
  await page.goto('fb://app' + vendorLink);
  await capture('14-vendor-activity');
  pass('D6 bills: vendor defaults, add-line, invalid values retained, save/revise/history, review/post, calendar, partial payment, shared check number, reverse and void via real forms');
  await go('/transfers/new/');
  await page.fill('#id_date', '2026-10-31');
  await page.fill('#id_amount', '30.25');
  await page.fill('#id_memo', 'Synthetic reserve transfer');
  await capture('15-transfer-form');
  await page.click('button:has-text("Review transfer")');
  await page.waitForSelector('#transfer-review');
  await capture('16-transfer-review');
  await save('Record transfer — books only', /transfers\/[0-9a-f-]{36}\/$/);
  const transferUrl = page.url();
  assert.equal(await page.locator('#transfer-amount').textContent(), '30.25');
  await capture('17-transfer-detail');
  await go('/transfers/');
  await capture('18-transfer-list');
  await page.goto(transferUrl);
  await page.click('a:has-text("Void transfer")');
  await page.waitForSelector('h1:has-text("Void transfer")');
  await page.fill('#id_date', '2026-10-31');
  await page.fill('#id_reason', 'Synthetic correction');
  await capture('19-transfer-void');
  await save('Void transfer', /transfers\/[0-9a-f-]{36}\/$/);
  assert.match(await heading(page), /Voided/);
  await capture('20-transfer-voided');
  pass('D6 transfer: review exact bank balances and entries, record, list, detail and linked void via real forms');
}
module.exports = async function (args) {
  const dialog = async d => { console.error('D6 unexpected dialog: ' + d.message()); await d.dismiss(); };
  args.page.on('dialog', dialog);
  try { await runD6(args); }
  catch (error) {
    const out = process.env.FB_SMOKE_SHOTS || path.resolve(__dirname, '../staging-run');
    fs.writeFileSync(path.join(out, 'd6-failure.html'), await args.page.content());
    await args.page.screenshot({path:path.join(out, 'd6-failure.png')});
    throw error;
  } finally { args.page.off('dialog', dialog); }
};
