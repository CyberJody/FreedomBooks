'use strict';
const assert=require('node:assert/strict');
module.exports=async ({page,company,ids,shot,pass})=>{
  const go=p=>page.goto(`fb://app/c/${company}${p}`);
  const row=kind=>page.locator('#document-numbering tr').filter({has:page.locator(`input[name="kind"][value="${kind}"]`)}).first();
  const save=async (kind,next)=>{
    const r=row(kind);await r.locator('[name="next_number"]').fill(next);
    await Promise.all([page.waitForURL(/edit\/#document-numbering$/),r.getByRole('button',{name:'Save number',exact:true}).click()]);
    await page.waitForFunction(({kind,next})=>Array.from(document.querySelectorAll('#document-numbering form')).some(form=>form.querySelector('[name="kind"]').value===kind && form.querySelector('[name="expected_next"]').value===next),{kind,next});
  };
  await go('/edit/');
  await page.locator('#document-numbering').scrollIntoViewIfNeeded();
  await shot(page,'numbers-01-settings');
  await save('INV','8100');
  assert.match(await row('INV').textContent(),/INV-008100/);
  await save('EST','8200');
  assert.match(await row('EST').textContent(),/EST-008200/);
  await go('/invoices/new/');
  await page.selectOption('#id_customer',ids.customer);
  await page.fill('#id_date','2026-10-31');await page.fill('#id_due_date','2026-11-30');
  await page.selectOption('#id_lines-0-item',ids.item);
  await page.fill('#id_memo','Synthetic numbered invoice');
  await page.selectOption('#id_lines-0-income_account',ids.income);
  await page.fill('#id_lines-0-quantity','1');await page.fill('#id_lines-0-rate','25.00');
  await Promise.all([page.waitForURL(/invoices\/[0-9a-f-]{36}\/$/),page.getByRole('button',{name:'Save invoice',exact:true}).click()]);
  assert.match(await page.locator('main h1').textContent(),/INV-008100/);
  await shot(page,'numbers-02-next-invoice');
  await go('/edit/');
  assert.match(await row('INV').textContent(),/INV-008101/);
  await row('INV').locator('[name="next_number"]').fill('8100');
  await row('INV').getByRole('button',{name:'Save number',exact:true}).click();
  await page.locator('#document-numbering .errorlist').waitFor();
  assert.match(await row('INV').textContent(),/already used.*INV-008100/);
  await row('INV').scrollIntoViewIfNeeded();await shot(page,'numbers-03-collision');
  await save('CHECK','9100');
  await row('CHECK').scrollIntoViewIfNeeded();
  await page.screenshot({path:require('node:path').join(process.env.FB_SMOKE_SHOTS,'numbers-01b-bank-settings.png')});
  await go('/checks/new/');
  await page.selectOption('#id_bank',ids.bank);
  assert.equal(await page.inputValue('#id_check_number'),'9100');
  await page.locator('input[name="payee_kind"][value="OTHER"]').check();await page.fill('#id_payee_name','Synthetic number test');
  await page.fill('#id_date','2026-10-31');await page.fill('#id_memo','Numbering smoke');
  await page.selectOption('#id_lines-0-account',ids.expense);await page.fill('#id_lines-0-rate','5.00');
  await Promise.all([page.waitForURL(/checks\/[0-9a-f-]{36}\/$/),page.getByRole('button',{name:'Save check',exact:true}).click()]);
  assert.match(await page.locator('main h1').textContent(),/9100/);
  await go('/edit/');assert.match(await row('CHECK').textContent(),/9101/);
  await go('/checks/');
  await page.locator('tbody tr').filter({hasText:'9100'}).getByRole('link').first().click();
  await page.getByRole('link',{name:'Edit check',exact:true}).click();
  await page.locator('#id_check_number').fill('9101');
  await Promise.all([page.waitForURL(/checks\/[0-9a-f-]{36}\/$/),page.getByRole('button',{name:'Save check',exact:true}).click()]);
  await go('/edit/');assert.match(await row('CHECK').textContent(),/9102/);
  await go('/history/');assert.match(await page.locator('main').textContent(),/Next document number changed/);
  await shot(page,'numbers-04-audit');
  pass('numbering: saved invoice/check starts, created documents, advanced next numbers, refused collision and audited changes');
};
