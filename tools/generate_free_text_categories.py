"""Generate Cc/Cf (except TAB) ranges from the frozen reference Python Unicode tables."""
from pathlib import Path
import sys, unicodedata

assert unicodedata.unidata_version == '15.1.0', 'Use the frozen reference Python environment'
ranges=[]
for cp in range(0x110000):
    if cp != 9 and unicodedata.category(chr(cp)) in ('Cc','Cf'):
        if ranges and ranges[-1][1] == cp-1:ranges[-1][1]=cp
        else:ranges.append([cp,cp])
text='// Generated by tools/generate_free_text_categories.py with frozen Python Unicode 15.1.0.\n'
text+='const FREE_TEXT_FORBIDDEN: &[(u32, u32)] = &[\n'
text+=''.join(f'    (0x{lo:x}, 0x{hi:x}),\n' for lo,hi in ranges)+'];\n'
target=Path(__file__).resolve().parents[1]/'crates/fb-db/src/free_text_categories.rs'
if '--check' in sys.argv:
    assert target.read_text()==text, 'Regenerate the free-text Unicode table'
    print('Free-text Unicode table matches frozen Python 15.1.0')
else:target.write_text(text)
