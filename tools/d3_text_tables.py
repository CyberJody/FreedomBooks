"""Generate the exact frozen Python Unicode data and Django truncation vectors.

Run with the reference Python 3.13 venv. It reads no application data and changes
only files in this worktree. Unicode tables must come from Python, not Rust's
possibly newer Unicode version (GUARD lesson 17).
"""
from pathlib import Path
import json
import random
import unicodedata as u
from django.conf import settings
if not settings.configured:settings.configure(USE_I18N=False)
from django.utils.text import Truncator

root=Path(__file__).resolve().parents[1]/'crates/fb-templates/src'
decompositions=[];compositions=[];combining=[]
for cp in range(0x110000):
    c=chr(cp);d=u.decomposition(c)
    if d and not d.startswith('<'):
        parts=[int(n,16) for n in d.split()];decompositions.append((cp,parts))
        if len(parts)==2 and u.normalize('NFC',''.join(map(chr,parts)))==c:compositions.append((*parts,cp))
    if u.combining(c):combining.append((cp,u.combining(c)))
text=f'// Generated by tools/d3_text_tables.py from Python unicodedata {u.unidata_version}. Do not edit.\n'
text+='pub(super) const DECOMP: &[(u32,&[u32])] = &[\n'+''.join(f'({cp},&{parts}),\n' for cp,parts in decompositions)+'];\n'
text+='pub(super) const COMPOSE: &[(u32,u32,u32)] = &[\n'+''.join(f'({a},{b},{cp}),\n' for a,b,cp in sorted(compositions))+'];\n'
text+='pub(super) const CCC: &[(u32,u8)] = &[\n'+''.join(f'({cp},{n}),\n' for cp,n in combining)+'];\n'
root.joinpath('d3_text_tables.rs').write_text(text)
rng=random.Random(31352)
alphabet=list('abcdeXYZ0123 …<&>')+['😀','\u0301','\u0327','\u0345','\u0308','\u0315','\u0300','\u1100','\u1161','\u11a8','\uac00','\ud7a3']
alphabet += [chr(cp) for cp,_ in decompositions]
vectors=[]
for value,n in [('e\u0301',4),('a\u0301\u0327bcde',3),('abcdef',0),('abcdef',1),('ab…c',3),('…abc',1)]:vectors.append([value,n,str(Truncator(value).chars(n))])
for cp,parts in decompositions:
    for value in [chr(cp),''.join(map(chr,parts))]:vectors.append([value,100,str(Truncator(value).chars(100))])
for _ in range(500):
    value=''.join(rng.choices(alphabet,k=rng.randrange(0,150)));n=rng.randrange(0,120);vectors.append([value,n,str(Truncator(value).chars(n))])
root.joinpath('d3_text_vectors.json').write_text(json.dumps(vectors,ensure_ascii=True)+'\n')
print(f'Frozen Unicode {u.unidata_version}: {len(decompositions)} decompositions, {len(compositions)} compositions, {len(combining)} combining classes; {len(vectors)} Django vectors')
