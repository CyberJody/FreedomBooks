"""Generate Python word-character provenance from the frozen interpreter (Unicode 14)."""
from pathlib import Path
import sys
import unicodedata

ranges = []
start = end = None
for value in range(sys.maxunicode + 1):
    if chr(value).isalnum():
        if start is None:
            start = value
        end = value
    elif start is not None:
        ranges.append((start, end))
        start = end = None
if start is not None:
    ranges.append((start, end))
out = f'// Generated by tools/d2_unicode.py, frozen Python Unicode {unicodedata.unidata_version}.\n'
out += 'pub fn is_alnum(c: char) -> bool {\n    let n=c as u32;\n    RANGES.binary_search_by(|(lo,hi)| if n<*lo {std::cmp::Ordering::Greater} else if n>*hi {std::cmp::Ordering::Less} else {std::cmp::Ordering::Equal}).is_ok()\n}\n'
out += 'const RANGES: &[(u32,u32)] = &[\n'
out += ''.join(f'    (0x{lo:x},0x{hi:x}),\n' for lo,hi in ranges)
out += '];\n'
Path('crates/fb-core/src/first_run_words.rs').write_text(out)
