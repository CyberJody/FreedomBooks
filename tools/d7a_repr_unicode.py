"""Generate Python repr's printability table from the frozen Python 3.13 Unicode data."""
from pathlib import Path
import sys,unicodedata
assert sys.version_info[:2]==(3,13)
assert unicodedata.unidata_version=='15.1.0'
ROOT=Path(__file__).resolve().parents[1]
ranges=[];start=None
for point in range(0x110000):
    bad=not chr(point).isprintable()
    if bad and start is None:start=point
    if not bad and start is not None:ranges.append((start,point-1));start=None
if start is not None:ranges.append((start,0x10ffff))
text='// Generated by tools/d7a_repr_unicode.py from frozen Python 3.13 / Unicode 15.1.0.\n'
text+='pub(super) const NONPRINTABLE: &[(u32,u32)] = &[\n'
text+=''.join(f'    (0x{a:x},0x{b:x}),\n' for a,b in ranges)+'];\n'
(ROOT/'crates/fb-templates/src/d7a_unicode.rs').write_text(text)
print(f'Generated {len(ranges)} frozen nonprintable ranges')
