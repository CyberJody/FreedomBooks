"""Write src/bankfeeds/html_tables.rs from Python's own html module (html.unescape's tables).

Run from crates/fb-core: python3 tools/html_tables.py
"""
import html
import html.entities
from pathlib import Path

remap = sorted(html._invalid_charrefs.items())
dropped = sorted(html._invalid_codepoints)
# Every named reference, by name without its `;`. The 93 that spell two characters all need the `;`
# (html.unescape reads them only with it); the one-character ones are read with or without it.
named = sorted({(k.removesuffix(";"), v) for k, v in html.entities.html5.items()})
multi = sum(1 for _, v in named if len(v) > 1)
assert all(len(v) in (1, 2) for _, v in named)
assert len({k for k, _ in named}) == len(named), "a name spells two different values"
assert all(k.endswith(";") for k, v in html.entities.html5.items() if len(v) > 1)


def ch(c):
    return "'\\u{%x}'" % ord(c)


def text(s):
    return '"' + "".join("\\u{%x}" % ord(c) for c in s) + '"'


def ranges(values):
    out, start, prev = [], None, None
    for v in values:
        if start is None:
            start = prev = v
        elif v == prev + 1:
            prev = v
        else:
            out.append((start, prev))
            start = prev = v
    out.append((start, prev))
    return out


lines = [
    "// Generated by tools/html_tables.py from Python's html module (the tables html.unescape uses). Do not edit.",
    "",
    "/// Numeric references HTML remaps (`html._invalid_charrefs`: NUL, CR and the Windows-1252 C1 range).",
    "pub const REMAP: &[(u32, char)] = &[",
]
lines += ["    (0x%x, %s)," % (k, ch(v)) for k, v in remap]
lines += [
    "];",
    "/// Code points `html.unescape` drops (`html._invalid_codepoints`), as inclusive ranges.",
    "pub const DROPPED: &[(u32, u32)] = &[",
]
lines += ["    (0x%x, 0x%x)," % r for r in ranges(dropped)]
lines += [
    "];",
    "/// Every named reference of HTML5 (`html.entities.html5`), by name without its `;`, sorted, with what",
    "/// it spells: one character (read with or without the `;`) or, for %d of them, two (read only with" % multi,
    "/// the `;`, as `html.unescape` reads them; no name spells two characters both ways).",
    "pub const NAMED: &[(&str, &str)] = &[",
]
lines += ['    ("%s", %s),' % (k, text(v)) for k, v in named]
lines += ["];", ""]
Path(__file__).resolve().parent.parent.joinpath("src/bankfeeds/html_tables.rs").write_text("\n".join(lines))
print(f"remap={len(remap)} dropped={len(dropped)} named={len(named)} two_character={multi}")
