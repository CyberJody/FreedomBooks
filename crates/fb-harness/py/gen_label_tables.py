"""Pin Python 3.13's str.isdigit and exceptional titlecase mappings for role labels."""
from pathlib import Path
ranges=[]
for c in range(0x110000):
    if chr(c).isdigit():
        if ranges and ranges[-1][1]+1==c:ranges[-1][1]=c
        else:ranges.append([c,c])
s='//! Generated by fb-harness/py/gen_label_tables.py from Python 3.13.\n'
s+='pub fn is_digit(c:char)->bool { matches!(c as u32, '+ '|'.join(f'0x{a:x}..=0x{b:x}'for a,b in ranges)+') }\n'
s+='pub fn titlecase(c:char)->String { match c {\n'
for c in range(0x110000):
    v=chr(c)
    if v.title()!=v.upper():
        target=''.join(f'\\u{{{ord(x):x}}}'for x in v.title())
        s+=f"'\\u{{{c:x}}}'=>\"{target}\".into(),\n"
s+='_=>c.to_uppercase().collect(),\n}}\n'
p=Path(__file__).resolve().parents[2]/'fb-core'/'src'/'python_digits.rs'
p.write_text(s)
print('Wrote',len(ranges),'digit ranges and exceptional titlecase mappings')
