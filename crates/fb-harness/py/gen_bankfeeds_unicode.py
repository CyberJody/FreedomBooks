"""Pin the frozen Python's Unicode (3.13, Unicode 15.1) for bank-feed text: `re` word characters, `\\s`,
`\\d`, `str.lower()` with its final-sigma context, and the NFKC check `urllib.parse._checknetloc` applies.

Writes crates/fb-core/src/bankfeeds/py_unicode.rs. Run with the answer key's interpreter:
    $FB_PY crates/fb-harness/py/gen_bankfeeds_unicode.py
"""
import re
import sys
import unicodedata
from pathlib import Path

assert sys.version_info[:2] == (3, 13), sys.version
assert unicodedata.unidata_version == '15.1.0', unicodedata.unidata_version


def ranges(pred):
    out = []
    for c in range(0x110000):
        if 0xD800 <= c <= 0xDFFF:
            continue
        if pred(chr(c)):
            if out and out[-1][1] + 1 == c:
                out[-1][1] = c
            else:
                out.append([c, c])
    return out


WORD = re.compile(r'\w')
SPACE = re.compile(r'\s')
DIGIT = re.compile(r'\d')
word = ranges(lambda ch: WORD.fullmatch(ch) is not None)
space = ranges(lambda ch: SPACE.fullmatch(ch) is not None)
digit = ranges(lambda ch: DIGIT.fullmatch(ch) is not None)


# Final sigma (`handle_capital_sigma` in unicodeobject.c) only asks two questions of a neighbour: is it
# case-ignorable (skipped), and otherwise is it cased. Probe both through str.lower() itself.
def final(s, index):
    return s.lower()[index] == 'ς'


ignorable = ranges(lambda ch: not final(ch + 'Σ', -1) and final('A' + ch + 'Σ', -1))
cased = ranges(lambda ch: final(ch + 'Σ', -1))
lower = [(c, chr(c).lower()) for c in range(0x110000)
         if not 0xD800 <= c <= 0xDFFF and c != 0x3A3 and chr(c).lower() != chr(c)]
nfkc_delims = ranges(lambda ch: any(d in unicodedata.normalize('NFKC', ch) for d in '/?#@:') and ch not in '/?#@:')


def table(name, rs):
    body = ','.join(f'(0x{a:x},0x{b:x})' for a, b in rs)
    return f'pub(crate) static {name}: &[(u32, u32)] = &[{body}];\n'


def esc(s):
    return ''.join(f'\\u{{{ord(x):x}}}' for x in s)


out = '//! Generated by fb-harness/py/gen_bankfeeds_unicode.py from Python 3.13 (Unicode 15.1). Do not edit.\n'
out += '#![allow(clippy::unreadable_literal)]\n'
out += table('WORD', word) + table('SPACE', space) + table('DIGIT', digit)
out += table('CASE_IGNORABLE', ignorable) + table('CASED', cased) + table('NFKC_DELIMITERS', nfkc_delims)
out += 'pub(crate) static LOWER: &[(u32, &str)] = &[' + ','.join(f'(0x{c:x},"{esc(v)}")' for c, v in lower) + '];\n'
path = Path(__file__).resolve().parents[2] / 'fb-core' / 'src' / 'bankfeeds' / 'py_unicode.rs'
path.write_text(out)
print('wrote', path, 'word', len(word), 'space', len(space), 'digit', len(digit), 'ignorable', len(ignorable),
      'cased', len(cased), 'lower', len(lower), 'nfkc', len(nfkc_delims))
