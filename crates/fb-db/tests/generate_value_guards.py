"""Generate migration 0130_shared_validators.sql: byte-exact value guards for every TEXT column.

    python3 crates/fb-db/tests/generate_value_guards.py

Installs every migration listed before 0130 in lib.rs into an empty SQLite database (stub UDFs and
collations, schema only), inventories each table's TEXT columns and classifies them by name:

  uuid       id, *_id, request_key        fb_valid_uuid       canonical lower-case hyphenated UUID
  date       date, *_date                 fb_valid_date       YYYY-MM-DD real calendar date, year >= 1
  timestamp  *_at                         fb_valid_timestamp  UTC ...SSZ / ...SS.ffffffZ, no leap second
  text       every other TEXT column      fb_valid_text       no NUL

Every class also rejects NUL (the predicates are total on the full stored bytes). Each table gets one
BEFORE INSERT and one BEFORE UPDATE guard and one arm of the open-time view `fb_value_invalid`.
`fb_value_guard_inventory.json` records the classification; the Rust inventory test recomputes it from the
live schema and requires both to agree, so a later table (bank feeds at INT-L4b) cannot be left out.
"""
import json
import re
import sqlite3
from pathlib import Path

HERE = Path(__file__).resolve().parent
FBDB = HERE.parent
MIGRATION = "0130_shared_validators"
MESSAGE = "fb_valid: Invalid stored text, identifier, date or timestamp"


def classify(column):
    # Seal/obligation bookkeeping doc_id: NUL-only (SEAL-DOCID-UUID deferral; tests use it as scratch markers).
    if column == "doc_id":
        return "text"
    if column == "id" or column.endswith("_id") or column == "request_key":
        return "uuid"
    if column == "date" or column.endswith("_date"):
        return "date"
    if column.endswith("_at"):
        return "timestamp"
    return "text"


FUNCTION = dict(uuid="fb_valid_uuid", date="fb_valid_date", timestamp="fb_valid_timestamp", text="fb_valid_text")


def schema():
    lib = (FBDB / "src" / "lib.rs").read_text()
    registry = lib.split("pub const MIGRATIONS")[1].split("];")[0]
    names = re.findall(r'\("(\d{4}_\w+)", include_str!', registry)
    names = [n for n in names if n < MIGRATION]
    sqls = [(FBDB / "sql" / f"{n}.sql").read_text() for n in names]
    conn = sqlite3.connect(":memory:")
    for fn in set(re.findall(r"\b(fb_\w+)\s*\(", "\n".join(sqls))):
        conn.create_function(fn, -1, lambda *args: 1, deterministic=True)
    for collation in set(re.findall(r"COLLATE\s+(\w+)", "\n".join(sqls), re.I)) - {"NOCASE", "BINARY", "RTRIM", "nocase", "binary", "rtrim"}:
        conn.create_collation(collation, lambda a, b: (a > b) - (a < b))
    for sql in sqls:
        conn.executescript(sql)
    tables = [r[0] for r in conn.execute("SELECT name FROM sqlite_schema WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name")]
    inventory = {}
    for table in tables:
        cols = [(r[1], r[2].upper()) for r in conn.execute(f'PRAGMA table_xinfo("{table}")')]
        text = {c: classify(c) for c, t in cols if t == "TEXT"}
        if text:
            inventory[table] = text
    return names, inventory


def condition(prefix, columns):
    return " OR\n ".join(f"NOT {FUNCTION[kind]}({prefix}{col})" for col, kind in columns.items())


def main():
    names, inventory = schema()
    out = [f"-- {MIGRATION}: shared byte-exact value guards (generated by tests/generate_value_guards.py).",
           "-- Every TEXT column of every table rejects NUL; identifiers, dates and timestamps are also checked",
           "-- against their canonical form. Adds triggers and one view only: no stored row changes."]
    arms = []
    for table, columns in inventory.items():
        for event in ("INSERT", "UPDATE"):
            out.append(f"CREATE TRIGGER fb_valid_{table}_{event.lower()} BEFORE {event} ON {table} BEGIN\n"
                       f" SELECT RAISE(ABORT,'{MESSAGE}') WHERE\n {condition('NEW.', columns)};\nEND;")
        arms.append(f"SELECT 'invalid stored value in {table}' AS problem FROM {table} WHERE\n {condition('', columns)}")
    out.append("CREATE VIEW fb_value_invalid AS\n" + "\nUNION ALL\n".join(arms) + ";")
    (FBDB / "sql" / f"{MIGRATION}.sql").write_text("\n".join(out) + "\n")
    (HERE / "fb_value_guard_inventory.json").write_text(json.dumps(inventory, indent=1, sort_keys=True) + "\n")
    counts = {}
    for columns in inventory.values():
        for kind in columns.values():
            counts[kind] = counts.get(kind, 0) + 1
    print(f"{len(names)} prior migrations, {len(inventory)} tables, {sum(counts.values())} TEXT columns {counts}")


if __name__ == "__main__":
    main()
